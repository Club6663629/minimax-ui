DEFAULT_SCENE = "general"


def apply_scene(prompt: str, scene: str) -> str:
    """把场景预设 skill 提示词拼到用户提示词前（无 skill 时原样返回）。"""
    cfg = SCENES.get(scene) or SCENES[DEFAULT_SCENE]
    skill = cfg.get("skill", "")
    if not skill:
        return prompt
    return f"{skill}\n\n用户需求：{prompt}"
